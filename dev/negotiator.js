// Runs the test suite of jshttp/negotiator in the directory given as the
// first argument, records each call that picks from offers for Accept or
// Accept-Language, and writes the calls with their results as a cljc
// namespace of test data to the file given as the second argument. See
// dev/negotiator.sh.
var fs = require('fs');
var path = require('path');
var dir = path.resolve(process.argv[2]);
var out = process.argv[3];
var version = require(path.join(dir, 'package.json')).version;
var Mocha = require(path.join(dir, 'node_modules', 'mocha'));
var Negotiator = require(dir);

var fields = {mediaType: 'accept', mediaTypes: 'accept',
              language: 'accept-language', languages: 'accept-language'};
var cases = [];

// Wrap each method, and record only the outermost call, since the
// singular methods call the plural ones.
var depth = 0;
Object.keys(fields).forEach(function (method) {
  var original = Negotiator.prototype[method];
  Negotiator.prototype[method] = function (offers) {
    depth++;
    var result;
    try {
      result = original.apply(this, arguments);
    } finally {
      depth--;
    }
    if (depth === 0 && offers) {
      var value = this.request.headers[fields[method]];
      cases.push({field: fields[method], value: value === undefined ? null : value,
                  method: method, offers: offers.slice(),
                  result: result === undefined ? null : result});
    }
    return result;
  };
});

function edn(x) {
  if (x === null) return 'nil';
  if (Array.isArray(x)) return '[' + x.map(edn).join(' ') + ']';
  // the escapes of JSON are valid in Clojure strings
  return JSON.stringify(x);
}

function caseEdn(c) {
  return '{:field ' + edn(c.field) + ' :value ' + edn(c.value) +
    ' :method ' + edn(c.method) + '\n    :offers ' + edn(c.offers) +
    '\n    :result ' + edn(c.result) + '}';
}

var license = fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8')
  .trim().split('\n').map(function (l) { return (';; ' + l).trimEnd(); }).join('\n');

var mocha = new Mocha({reporter: 'dot'});
['mediaType', 'language'].forEach(function (file) {
  mocha.addFile(path.join(dir, 'test', file + '.js'));
});
mocha.run(function (failures) {
  if (failures) {
    console.error('negotiator failed ' + failures + ' of its own tests');
    process.exit(1);
  }
  fs.writeFileSync(out,
    ';; Generated by dev/negotiator.sh from the test suite of jshttp/negotiator\n' +
    ';; ' + version + '. Edit the script rather than this file.\n;;\n' +
    license + '\n\n' +
    '(ns dk.simongray.conneg.negotiator-cases\n' +
    '  "The calls of jshttp/negotiator\'s test suite that pick from offers for\n' +
    '  Accept or Accept-Language, with negotiator\'s results.")\n\n' +
    '(def cases\n' +
    '  "Maps of the :field, its :value, the :method of negotiator, the :offers\n' +
    '  and the :result: an offer or nil for mediaType and language, and the\n' +
    '  acceptable offers, best first, for mediaTypes and languages."\n' +
    '  [' + cases.map(caseEdn).join('\n   ') + '])\n');
});
